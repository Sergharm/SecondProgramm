def p(text, style=''):
    return f'<p class="{style}">{escape(text).replace(chr(10), "<br>")}</p>'


def table(headers, rows, widths, plain=False, style=None):
    def row(tag, cells):
        return '<tr>' + ''.join(f'<{tag}>{escape(c).replace(chr(10), "<br>")}</{tag}>' for c in cells) + '</tr>'

    table_style = style or (plain if isinstance(plain, str) else 'plain' if plain else 'ruled')
    return (f'<table class="{table_style}" data-widths="{widths}">'
            + (f'<thead>{row("th", headers)}</thead>' if headers else '')
            + '<tbody>' + ''.join(row('td', cells) for cells in rows) + '</tbody></table>')


